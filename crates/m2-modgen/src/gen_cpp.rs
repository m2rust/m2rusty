//! C header + C++ marshalling shim generator.

use crate::abi::{c_type, cfg_to_if, module_ident, plan, unique_names, Ov, Plan};
use crate::spec::{Constant, Function, ModuleSpec, Param, Ty};
use std::fmt::Write as _;
use std::path::Path;

pub const SHIM_H: &str = r#"/* Generated by m2-modgen. The C ABI between the Python marshalling shims and the Rust logic. */
#ifndef M2_SHIM_H
#define M2_SHIM_H

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

#ifdef __cplusplus
extern "C" {
#endif

/* What a logic function reports. Everything but M2_OK means "no value":
 *   M2_NONE           the shim returns None (Py_BuildException() with no message);
 *   M2_RUNTIME_ERROR  RuntimeError(message) is set, None is returned (Py_BuildException(msg), as the C++ does);
 *   M2_VALUE_ERROR    ValueError(message) is raised;
 *   M2_TYPE_ERROR     TypeError(message) is raised;
 *   M2_PYERR          the callee already set a Python error; NULL is returned. */
enum {
    M2_OK = 0,
    M2_NONE = 1,
    M2_RUNTIME_ERROR = 2,
    M2_VALUE_ERROR = 3,
    M2_TYPE_ERROR = 4,
    M2_PYERR = 5
};

typedef struct m2_result {
    int32_t kind;
    const char *message; /* valid until the next call; may be NULL */
} m2_result;

#ifdef __cplusplus
}
#endif

#endif
"#;

pub const SHIM_HPP: &str = r#"// Generated by m2-modgen. Helpers shared by the generated shims.
#pragma once

#include <Python.h>

#include "m2_shim.h"

// Same declarations as Neoeter/Python/Host/PythonUtils.h (the host provides the definitions).
bool PyTuple_GetString(PyObject *poArgs, int pos, char **ret);
bool PyTuple_GetInteger(PyObject *poArgs, int pos, unsigned short *ret);
bool PyTuple_GetInteger(PyObject *poArgs, int pos, int *ret);
bool PyTuple_GetByte(PyObject *poArgs, int pos, unsigned char *ret);
bool PyTuple_GetUnsignedInteger(PyObject *poArgs, int pos, unsigned int *ret);
bool PyTuple_GetLong(PyObject *poArgs, int pos, long *ret);
bool PyTuple_GetUnsignedLong(PyObject *poArgs, int pos, unsigned long *ret);
bool PyTuple_GetFloat(PyObject *poArgs, int pos, float *ret);
bool PyTuple_GetDouble(PyObject *poArgs, int pos, double *ret);
bool PyTuple_GetObject(PyObject *poArgs, int pos, PyObject **ret);
bool PyTuple_GetBoolean(PyObject *poArgs, int pos, bool *ret);
PyObject *Py_BuildException(const char *c_pszErr, ...);
PyObject *Py_BadArgument();
PyObject *Py_BuildNone();

static inline PyObject *m2_shim_fail(m2_result r)
{
    const char *msg = r.message ? r.message : "";
    switch (r.kind)
    {
    case M2_RUNTIME_ERROR:
        return Py_BuildException("%s", msg);
    case M2_VALUE_ERROR:
        PyErr_SetString(PyExc_ValueError, msg);
        return nullptr;
    case M2_TYPE_ERROR:
        PyErr_SetString(PyExc_TypeError, msg);
        return nullptr;
    case M2_PYERR:
        return nullptr;
    default:
        return Py_BuildException(nullptr);
    }
}
"#;

fn fail_expr(on_bad: &str) -> &'static str {
    match on_bad {
        "bad_argument" => "Py_BadArgument()",
        "parse_tuple" | "null" => "nullptr",
        _ => "Py_BuildException(nullptr)",
    }
}

fn tmp_decl(t: &Ty, n: &str) -> String {
    match t {
        Ty::Int => format!("int {n} = 0;"),
        Ty::Uint => format!("unsigned int {n} = 0;"),
        Ty::Long | Ty::Handle(_) => format!("long {n} = 0;"),
        Ty::Ulong => format!("unsigned long {n} = 0;"),
        Ty::Byte => format!("unsigned char {n} = 0;"),
        Ty::Word => format!("unsigned short {n} = 0;"),
        Ty::Float => format!("float {n} = 0;"),
        Ty::Double => format!("double {n} = 0;"),
        Ty::Bool => format!("bool {n} = false;"),
        Ty::Str => format!("char *{n} = nullptr;"),
        Ty::Object => format!("PyObject *{n} = nullptr;"),
        _ => format!("/* unsupported */ int {n} = 0;"),
    }
}

fn get_expr(t: &Ty, i: usize, n: &str) -> String {
    match t {
        Ty::Int | Ty::Word => format!("PyTuple_GetInteger(poArgs, {i}, &{n})"),
        Ty::Uint => format!("PyTuple_GetUnsignedInteger(poArgs, {i}, &{n})"),
        Ty::Long => format!("PyTuple_GetLong(poArgs, {i}, &{n})"),
        Ty::Handle(_) => format!("(PyTuple_GetLong(poArgs, {i}, &{n}) && {n} != 0)"),
        Ty::Ulong => format!("PyTuple_GetUnsignedLong(poArgs, {i}, &{n})"),
        Ty::Byte => format!("PyTuple_GetByte(poArgs, {i}, &{n})"),
        Ty::Float => format!("PyTuple_GetFloat(poArgs, {i}, &{n})"),
        Ty::Double => format!("PyTuple_GetDouble(poArgs, {i}, &{n})"),
        Ty::Bool => format!("PyTuple_GetBoolean(poArgs, {i}, &{n})"),
        Ty::Str => format!("PyTuple_GetString(poArgs, {i}, &{n})"),
        Ty::Object => format!("PyTuple_GetObject(poArgs, {i}, &{n})"),
        _ => "false".into(),
    }
}

fn parse_char(t: &Ty) -> char {
    match t {
        Ty::Int => 'i',
        Ty::Uint => 'I',
        Ty::Long => 'l',
        Ty::Ulong => 'k',
        Ty::Byte => 'b',
        Ty::Word => 'H',
        Ty::Float => 'f',
        Ty::Double => 'd',
        Ty::Str => 's',
        _ => 'O',
    }
}

fn value_fmt(t: &Ty) -> (&'static str, &'static str) {
    // (format char, cast)
    match t {
        Ty::Int => ("i", "int"),
        Ty::Uint => ("I", "unsigned int"),
        Ty::Long | Ty::Handle(_) => ("l", "long"),
        Ty::Ulong => ("k", "unsigned long"),
        Ty::Byte => ("b", "int"),
        Ty::Word => ("h", "int"),
        Ty::Float => ("f", "double"),
        Ty::Double => ("d", "double"),
        Ty::Bool => ("i", "int"),
        Ty::Str => ("s", "const char *"),
        _ => ("O", "PyObject *"),
    }
}

fn elem_ctor(t: &Ty, v: &str) -> String {
    match t {
        Ty::Float | Ty::Double => format!("PyFloat_FromDouble((double){v})"),
        Ty::Str => format!("PyString_FromString({v} ? {v} : \"\")"),
        Ty::Bool => format!("PyBool_FromLong({v})"),
        Ty::Uint | Ty::Ulong | Ty::Handle(_) => format!("PyLong_FromUnsignedLong((unsigned long){v})"),
        _ => format!("PyInt_FromLong((long){v})"),
    }
}

fn c_param_decl(p: &Param, idx: usize) -> String {
    if p.optional && !matches!(p.ty, Ty::Str | Ty::Object) {
        format!("const {} *p{idx}", c_type(&p.ty))
    } else {
        format!("{} p{idx}", c_type(&p.ty))
    }
}

/// `out` parameter declarations for a return type.
fn out_decls(ret: &Ty) -> Vec<String> {
    match ret {
        Ty::None => vec![],
        Ty::Str => vec!["const char **out0".into()],
        Ty::Bytes => vec!["const uint8_t **out0".into(), "size_t *out0_len".into()],
        Ty::Tuple(v) => v
            .iter()
            .enumerate()
            .map(|(i, t)| if *t == Ty::Str { format!("const char **out{i}") } else { format!("{} *out{i}", c_type(t)) })
            .collect(),
        Ty::List(e) => {
            if **e == Ty::Str {
                vec!["const char *const **out0".into(), "size_t *out0_len".into()]
            } else {
                vec![format!("const {} **out0", c_type(e)), "size_t *out0_len".into()]
            }
        }
        t => vec![format!("{} *out0", c_type(t))],
    }
}

fn c_decl(module: &str, ov: &Ov, ret: &Ty, f: &Function) -> String {
    let mut args: Vec<String> = ov.params.iter().enumerate().map(|(i, p)| c_param_decl(p, i)).collect();
    args.extend(out_decls(ret));
    if args.is_empty() {
        args.push("void".into());
    }
    let sig: Vec<String> = ov.params.iter().map(|p| p.to_string()).collect();
    format!(
        "/* {}.{}({}) -> {}{} */\nm2_result m2_{}_{}({});",
        module,
        f.name,
        sig.join(", "),
        f.returns,
        if f.returns_none { " (or None)" } else { "" },
        module_ident(module),
        ov.c_name,
        args.join(", ")
    )
}

pub fn header(spec: &ModuleSpec, plans: &[(usize, Plan)]) -> String {
    let mut o = String::new();
    let _ = writeln!(o, "/* Generated by m2-modgen from modules/{}.toml. Implemented by the Rust side. */", spec.module);
    let g = format!("M2_{}_H", module_ident(&spec.module).to_uppercase());
    let _ = writeln!(o, "#ifndef {g}\n#define {g}\n\n#include \"m2_shim.h\"\n\n#ifdef __cplusplus\nextern \"C\" {{\n#endif\n");
    for (fi, p) in plans {
        let f = &spec.functions[*fi];
        for ov in &p.ovs {
            if !f.cfg.is_empty() {
                let _ = writeln!(o, "#if {}", cfg_to_if(&f.cfg));
            }
            let _ = writeln!(o, "{}", c_decl(&spec.module, ov, &p.ret, f));
            if !f.cfg.is_empty() {
                let _ = writeln!(o, "#endif");
            }
        }
    }
    let _ = writeln!(o, "\n#ifdef __cplusplus\n}}\n#endif\n\n#endif");
    o
}

fn overload_body(module: &str, f: &Function, ov: &Ov, ret: &Ty, ind: &str) -> String {
    let fail = fail_expr(&f.on_bad_arg);
    let mut o = String::new();
    let n = ov.params.len();
    let parse_tuple = f.on_bad_arg == "parse_tuple";
    for (i, p) in ov.params.iter().enumerate() {
        let _ = writeln!(o, "{ind}{}", tmp_decl(&p.ty, &format!("t{i}")));
    }
    if parse_tuple {
        let mut fmt = String::new();
        let mut opt = false;
        for p in &ov.params {
            if p.optional && !opt {
                fmt.push('|');
                opt = true;
            }
            fmt.push(parse_char(&p.ty));
        }
        let ptrs: Vec<String> = (0..n).map(|i| format!("&t{i}")).collect();
        let _ = writeln!(o, "{ind}if (!PyArg_ParseTuple(poArgs, \"{fmt}:{}\"{}{}))\n{ind}    return nullptr;", f.name, if n > 0 { ", " } else { "" }, ptrs.join(", "));
        for (i, p) in ov.params.iter().enumerate() {
            if p.optional {
                let _ = writeln!(o, "{ind}const bool h{i} = PyTuple_Size(poArgs) > {i};");
            }
        }
    } else {
        for (i, p) in ov.params.iter().enumerate() {
            let g = get_expr(&p.ty, i, &format!("t{i}"));
            if p.optional {
                let _ = writeln!(o, "{ind}const bool h{i} = {g};");
            } else {
                let _ = writeln!(o, "{ind}if (!{g})\n{ind}    return {fail};");
            }
        }
    }
    // ABI arguments.
    let mut call_args = Vec::new();
    for (i, p) in ov.params.iter().enumerate() {
        let cast = match &p.ty {
            Ty::Str => String::new(),
            Ty::Object => "(void *)".to_string(),
            t => format!("({})", c_type(t)),
        };
        if p.optional {
            match p.ty {
                Ty::Str => call_args.push(format!("h{i} ? t{i} : nullptr")),
                Ty::Object => call_args.push(format!("h{i} ? (void *)t{i} : nullptr")),
                _ => {
                    let _ = writeln!(o, "{ind}const {} v{i} = {cast}t{i};", c_type(&p.ty));
                    call_args.push(format!("h{i} ? &v{i} : nullptr"));
                }
            }
        } else {
            call_args.push(format!("{cast}t{i}"));
        }
    }
    // Outputs.
    let mut post = String::new();
    match ret {
        Ty::None => {}
        Ty::Str => {
            let _ = writeln!(o, "{ind}const char *o0 = nullptr;");
            call_args.push("&o0".into());
        }
        Ty::Bytes => {
            let _ = writeln!(o, "{ind}const uint8_t *o0 = nullptr;\n{ind}size_t o0_len = 0;");
            call_args.push("&o0".into());
            call_args.push("&o0_len".into());
        }
        Ty::Tuple(v) => {
            for (i, t) in v.iter().enumerate() {
                let ty = if *t == Ty::Str { "const char *".to_string() } else { c_type(t).to_string() };
                let _ = writeln!(o, "{ind}{ty} o{i}{};", if *t == Ty::Str { " = nullptr" } else { "{}" });
                call_args.push(format!("&o{i}"));
            }
        }
        Ty::List(e) => {
            if **e == Ty::Str {
                let _ = writeln!(o, "{ind}const char *const *o0 = nullptr;");
            } else {
                let _ = writeln!(o, "{ind}const {} *o0 = nullptr;", c_type(e));
            }
            let _ = writeln!(o, "{ind}size_t o0_len = 0;");
            call_args.push("&o0".into());
            call_args.push("&o0_len".into());
        }
        t => {
            let _ = writeln!(o, "{ind}{} o0{{}};", c_type(t));
            call_args.push("&o0".into());
        }
    }
    let _ = writeln!(o, "{ind}const m2_result r = m2_{}_{}({});", module_ident(module), ov.c_name, call_args.join(", "));
    let _ = writeln!(o, "{ind}if (r.kind != M2_OK)\n{ind}    return m2_shim_fail(r);");
    match ret {
        Ty::None => post.push_str(&format!("{ind}return Py_BuildNone();\n")),
        Ty::Bool => post.push_str(&format!("{ind}return PyBool_FromLong(o0);\n")),
        Ty::Str => post.push_str(&format!("{ind}return Py_BuildValue(\"s\", o0);\n")),
        Ty::Bytes => post.push_str(&format!("{ind}return Py_BuildValue(\"s#\", (const char *)o0, (int)o0_len);\n")),
        Ty::Tuple(v) => {
            let fmts: String = v.iter().map(|t| value_fmt(t).0).collect();
            let args: Vec<String> = v
                .iter()
                .enumerate()
                .map(|(i, t)| {
                    let c = value_fmt(t).1;
                    if *t == Ty::Str { format!("o{i}") } else { format!("({c})o{i}") }
                })
                .collect();
            post.push_str(&format!("{ind}return Py_BuildValue(\"({fmts})\"{}{});\n", if args.is_empty() { "" } else { ", " }, args.join(", ")));
        }
        Ty::List(e) => {
            post.push_str(&format!("{ind}PyObject *list = PyList_New(0);\n"));
            post.push_str(&format!("{ind}for (size_t k = 0; k < o0_len; ++k)\n{ind}{{\n"));
            post.push_str(&format!("{ind}    PyObject *item = {};\n", elem_ctor(e, "o0[k]")));
            post.push_str(&format!("{ind}    PyList_Append(list, item);\n{ind}    Py_DECREF(item);\n{ind}}}\n{ind}return list;\n"));
        }
        t => {
            let (fm, c) = value_fmt(t);
            post.push_str(&format!("{ind}return Py_BuildValue(\"{fm}\", ({c})o0);\n"));
        }
    }
    o.push_str(&post);
    o
}

fn shim_fn(module: &str, f: &Function, plan: &Result<Plan, String>) -> String {
    let mut o = String::new();
    let _ = writeln!(o, "static PyObject *m2gen_{}(PyObject *poSelf, PyObject *poArgs)\n{{", f.cfunc);
    match plan {
        Err(why) => {
            let _ = writeln!(o, "    // Not generated: {why}.");
            let _ = writeln!(o, "    return Py_BuildException(\"{}.{}: not generated yet\");", module, f.name);
        }
        Ok(p) if p.ovs.len() == 1 => {
            o.push_str(&overload_body(module, f, &p.ovs[0], &p.ret, "    "));
        }
        Ok(p) => {
            let _ = writeln!(o, "    switch (PyTuple_Size(poArgs))\n    {{");
            for ov in &p.ovs {
                let _ = writeln!(o, "    case {}:\n    {{", ov.arity);
                o.push_str(&overload_body(module, f, ov, &p.ret, "        "));
                let _ = writeln!(o, "    }}");
            }
            let _ = writeln!(o, "    default:\n        return {};\n    }}", fail_expr(&f.on_bad_arg));
        }
    }
    let _ = writeln!(o, "}}");
    o
}

fn constant_stmt(c: &Constant) -> Option<String> {
    if c.value.is_empty() {
        return None;
    }
    let st = match c.ty.as_str() {
        "int" => format!("PyModule_AddIntConstant(poModule, \"{}\", {}L);", c.name, c.value),
        "float" => format!("PyModule_AddObject(poModule, \"{}\", PyFloat_FromDouble({}));", c.name, c.value),
        "str" => format!("PyModule_AddStringConstant(poModule, \"{}\", \"{}\");", c.name, c.value.replace('\\', "\\\\").replace('"', "\\\"")),
        _ => return None,
    };
    Some(st)
}

pub struct Generated {
    pub header: String,
    pub source: String,
    /// (function, reason) for everything that became a stub.
    pub stubs: Vec<(String, String)>,
}

pub fn generate_module(spec: &ModuleSpec, prefix: &str) -> Generated {
    let mut plans: Vec<(usize, Plan)> = Vec::new();
    let mut results: Vec<Result<(), String>> = Vec::new();
    let mut seen_cfuncs = std::collections::BTreeSet::new();
    for (i, f) in spec.functions.iter().enumerate() {
        if !seen_cfuncs.insert(f.cfunc.clone()) {
            results.push(Err("alias".into()));
            continue;
        }
        match plan(f) {
            Ok(p) => {
                plans.push((i, p));
                results.push(Ok(()));
            }
            Err(e) => results.push(Err(e)),
        }
    }
    unique_names(&mut plans);
    let mut stubs = Vec::new();
    let mut src = String::new();
    let ident = module_ident(&spec.module);
    let _ = writeln!(src, "// Generated by m2-modgen from modules/{}.toml. Do not edit.", spec.module);
    let _ = writeln!(src, "#include \"m2_shim.hpp\"\n#include \"m2_{ident}.h\"\n");
    for (i, f) in spec.functions.iter().enumerate() {
        let pl = plans.iter().position(|(k, _)| *k == i);
        let planned: Result<Plan, String> = match pl {
            Some(pos) => {
                let (_, p) = &plans[pos];
                Ok(Plan { ovs: p.ovs.iter().map(|o| Ov { c_name: o.c_name.clone(), rust_name: o.rust_name.clone(), params: o.params.clone(), arity: o.arity }).collect(), ret: p.ret.clone(), returns_none: p.returns_none })
            }
            None => Err(results[i].clone().unwrap_err()),
        };
        if let Err(e) = &planned {
            if e == "alias" {
                continue; // same C++ function as an earlier table entry; the table points at the one shim
            }
            stubs.push((format!("{}.{}", spec.module, f.name), e.clone()));
        }
        if !f.cfg.is_empty() {
            let _ = writeln!(src, "#if {}", cfg_to_if(&f.cfg));
        }
        src.push_str(&shim_fn(&spec.module, f, &planned));
        if !f.cfg.is_empty() {
            let _ = writeln!(src, "#endif");
        }
        src.push('\n');
    }
    let pyname = format!("{prefix}{}", spec.module);
    if prefix.is_empty() {
        let _ = writeln!(src, "void init{pyname}()\n{{");
    } else {
        let _ = writeln!(src, "extern \"C\" PyMODINIT_FUNC init{pyname}(void)\n{{");
    }
    let _ = writeln!(src, "    static PyMethodDef s_methods[] = {{");
    for f in &spec.functions {
        if !f.cfg.is_empty() {
            let _ = writeln!(src, "#if {}", cfg_to_if(&f.cfg));
        }
        let fl = if f.flags == "noargs" { "METH_NOARGS" } else { "METH_VARARGS" };
        let _ = writeln!(src, "        {{\"{}\", m2gen_{}, {fl}}},", f.name, f.cfunc);
        if !f.cfg.is_empty() {
            let _ = writeln!(src, "#endif");
        }
    }
    let _ = writeln!(src, "        {{nullptr, nullptr, 0}},\n    }};\n");
    let _ = writeln!(src, "    PyObject *poModule = Py_InitModule(\"{pyname}\", s_methods);");
    let _ = writeln!(src, "    (void)poModule;");
    for c in &spec.constants {
        if let Some(st) = constant_stmt(c) {
            if !c.cfg.is_empty() {
                let _ = writeln!(src, "#if {}", cfg_to_if(&c.cfg));
            }
            let _ = writeln!(src, "    {st}");
            if !c.cfg.is_empty() {
                let _ = writeln!(src, "#endif");
            }
        }
    }
    let _ = writeln!(src, "}}");
    Generated { header: header(spec, &plans), source: src, stubs }
}

pub fn write_all(specs: &[ModuleSpec], out: &Path, prefix: &str) -> Result<(), String> {
    let inc = out.join("include");
    let cpp = out.join("cpp");
    std::fs::create_dir_all(&inc).map_err(|e| e.to_string())?;
    std::fs::create_dir_all(&cpp).map_err(|e| e.to_string())?;
    std::fs::write(inc.join("m2_shim.h"), SHIM_H).map_err(|e| e.to_string())?;
    std::fs::write(inc.join("m2_shim.hpp"), SHIM_HPP).map_err(|e| e.to_string())?;
    let mut stubs = Vec::new();
    for s in specs.iter().filter(|s| !s.module.starts_with('(') && !s.functions.is_empty()) {
        let g = generate_module(s, prefix);
        let id = module_ident(&s.module);
        std::fs::write(inc.join(format!("m2_{id}.h")), g.header).map_err(|e| e.to_string())?;
        std::fs::write(cpp.join(format!("{id}_shim.cpp")), g.source).map_err(|e| e.to_string())?;
        stubs.extend(g.stubs);
    }
    eprintln!("C++ shims written; {} functions left as stubs", stubs.len());
    for (f, why) in stubs {
        eprintln!("  stub {f}: {why}");
    }
    Ok(())
}
