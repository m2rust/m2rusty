//! Rust trait + `extern "C"` glue skeleton generator.
//!
//! One file per module: a trait with a method per function/overload (default
//! bodies fail with "not implemented"), a thread-local slot holding the
//! implementation, and `#[unsafe(no_mangle)] extern "C"` functions matching the
//! generated C header.

use crate::abi::{module_ident, plan, rust_ident, rust_param_names, rust_type, unique_names, Plan};
use crate::spec::{ModuleSpec, Ty};
use std::fmt::Write as _;
use std::path::Path;

pub const SUPPORT_RS: &str = r#"//! Generated by m2-modgen. Shared glue types.
#![allow(dead_code, clippy::missing_safety_doc, clippy::not_unsafe_ptr_arg_deref, clippy::too_many_arguments)]

use std::any::Any;
use std::cell::RefCell;
use std::ffi::{CStr, CString, c_char, c_void};

/// What a logic function reports instead of a value (see `m2_shim.h`).
#[derive(Debug, Clone, PartialEq)]
pub enum PyError {
    /// Return None to Python.
    None,
    /// RuntimeError(message); the C++ shim still returns None (`Py_BuildException`).
    Runtime(String),
    ValueError(String),
    TypeError(String),
    /// A Python error is already set.
    Pending,
    NotImplemented(&'static str),
}

pub type PyResult<T> = Result<T, PyError>;

/// A borrowed `PyObject *`; only valid during the call, main thread only.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct PyObj(pub *mut c_void);

#[repr(C)]
pub struct M2Result {
    pub kind: i32,
    pub message: *const c_char,
}

thread_local! {
    static MESSAGE: RefCell<CString> = RefCell::new(CString::default());
    static KEEP: RefCell<Option<Box<dyn Any>>> = const { RefCell::new(None) };
}

pub fn ok() -> M2Result {
    M2Result { kind: 0, message: std::ptr::null() }
}

pub fn fail(e: PyError) -> M2Result {
    let (kind, msg) = match e {
        PyError::None => (1, String::new()),
        PyError::Runtime(m) => (2, m),
        PyError::ValueError(m) => (3, m),
        PyError::TypeError(m) => (4, m),
        PyError::Pending => (5, String::new()),
        PyError::NotImplemented(n) => (2, format!("{n}: not implemented")),
    };
    let c = CString::new(msg.replace('\0', " ")).unwrap_or_default();
    let p = MESSAGE.with(|m| {
        *m.borrow_mut() = c;
        m.borrow().as_ptr()
    });
    M2Result { kind, message: p }
}

pub fn no_api(module: &'static str) -> M2Result {
    fail(PyError::Runtime(format!("{module}: no API installed")))
}

/// Lossy so a non-UTF-8 byte string cannot cause a panic (legacy code pages are converted at the file boundary).
pub unsafe fn cstr(p: *const c_char) -> String {
    if p.is_null() { String::new() } else { String::from_utf8_lossy(unsafe { CStr::from_ptr(p) }.to_bytes()).into_owned() }
}

pub unsafe fn opt_cstr(p: *const c_char) -> Option<String> {
    if p.is_null() { None } else { Some(unsafe { cstr(p) }) }
}

pub unsafe fn opt<T: Copy>(p: *const T) -> Option<T> {
    if p.is_null() { None } else { Some(unsafe { *p }) }
}

/// Keeps `v` alive until the next call on this thread and returns a pointer to it.
pub fn keep_str(s: String) -> *const c_char {
    let c = CString::new(s.replace('\0', " ")).unwrap_or_default();
    let b = Box::new(c);
    let p = b.as_ptr();
    KEEP.with(|k| *k.borrow_mut() = Some(b));
    p
}

pub fn keep_bytes(v: Vec<u8>) -> (*const u8, usize) {
    let b = Box::new(v);
    let r = (b.as_ptr(), b.len());
    KEEP.with(|k| *k.borrow_mut() = Some(b));
    r
}

pub fn keep_vec<T: 'static>(v: Vec<T>) -> (*const T, usize) {
    let b = Box::new(v);
    let r = (b.as_ptr(), b.len());
    KEEP.with(|k| *k.borrow_mut() = Some(b));
    r
}

pub fn keep_strs(v: Vec<String>) -> (*const *const c_char, usize) {
    struct Strs(Vec<CString>, Vec<*const c_char>);
    let cs: Vec<CString> = v.into_iter().map(|s| CString::new(s.replace('\0', " ")).unwrap_or_default()).collect();
    let ps: Vec<*const c_char> = cs.iter().map(|c| c.as_ptr()).collect();
    let b = Box::new(Strs(cs, ps));
    let r = (b.1.as_ptr(), b.1.len());
    KEEP.with(|k| *k.borrow_mut() = Some(b));
    r
}
"#;

fn doc_sig(module: &str, f: &crate::spec::Function, params: &[crate::spec::Param]) -> String {
    let p: Vec<String> = params.iter().map(|p| p.to_string()).collect();
    format!("{module}.{}({}) -> {}", f.name, p.join(", "), f.returns)
}

fn trait_ret(ret: &Ty) -> String {
    match ret {
        Ty::None => "()".into(),
        Ty::Str => "String".into(),
        Ty::Bytes => "Vec<u8>".into(),
        Ty::Tuple(v) => {
            let items: Vec<String> = v.iter().map(|t| if *t == Ty::Str { "String".into() } else { rust_type(t).to_string() }).collect();
            if items.len() == 1 { format!("({},)", items[0]) } else { format!("({})", items.join(", ")) }
        }
        Ty::List(e) => format!("Vec<{}>", if **e == Ty::Str { "String" } else { rust_type(e) }),
        t => rust_type(t).into(),
    }
}

fn trait_param(p: &crate::spec::Param) -> String {
    let base = match &p.ty {
        Ty::Str => "String".to_string(),
        Ty::Object => "PyObj".to_string(),
        t => rust_type(t).to_string(),
    };
    if p.optional { format!("Option<{base}>") } else { base }
}

fn glue_param(p: &crate::spec::Param) -> String {
    match (&p.ty, p.optional) {
        (Ty::Str, _) => "*const c_char".into(),
        (Ty::Object, _) => "*mut c_void".into(),
        (t, true) => format!("*const {}", rust_type(t)),
        (t, false) => rust_type(t).into(),
    }
}

fn glue_convert(p: &crate::spec::Param, name: &str) -> String {
    match (&p.ty, p.optional) {
        (Ty::Str, false) => format!("unsafe {{ cstr({name}) }}"),
        (Ty::Str, true) => format!("unsafe {{ opt_cstr({name}) }}"),
        (Ty::Object, false) => format!("PyObj({name})"),
        (Ty::Object, true) => format!("if {name}.is_null() {{ None }} else {{ Some(PyObj({name})) }}"),
        (_, true) => format!("unsafe {{ opt({name}) }}"),
        (_, false) => name.to_string(),
    }
}

fn glue_outs(ret: &Ty) -> Vec<(String, String)> {
    // (param declaration, write statement template using `v`)
    match ret {
        Ty::None => vec![],
        _ => vec![],
    }
}

pub fn generate_module(spec: &ModuleSpec) -> String {
    let ident = module_ident(&spec.module);
    let mut plans: Vec<(usize, Plan)> = Vec::new();
    let mut skipped = Vec::new();
    let mut seen_cfuncs = std::collections::BTreeSet::new();
    for (i, f) in spec.functions.iter().enumerate() {
        if !seen_cfuncs.insert(f.cfunc.clone()) {
            continue; // alias of an earlier table entry
        }
        match plan(f) {
            Ok(p) => plans.push((i, p)),
            Err(e) => skipped.push((f.name.clone(), e)),
        }
    }
    unique_names(&mut plans);
    let tname = {
        let mut s = String::new();
        let mut up = true;
        for c in ident.chars() {
            if c == '_' {
                up = true;
            } else if up {
                s.extend(c.to_uppercase());
                up = false;
            } else {
                s.push(c);
            }
        }
        format!("{s}Api")
    };
    let mut o = String::new();
    let _ = writeln!(o, "//! Generated by m2-modgen from modules/{}.toml. Do not edit.", spec.module);
    let _ = writeln!(o, "#![allow(unused_variables, unused_unsafe, clippy::all)]\n");
    let _ = writeln!(o, "use super::support::*;\nuse std::cell::RefCell;\nuse std::ffi::{{c_char, c_void}};\n");
    let _ = writeln!(o, "/// Logic behind the Python module `{}`. Every method defaults to \"not implemented\".", spec.module);
    let _ = writeln!(o, "pub trait {tname} {{");
    for (fi, p) in &plans {
        let f = &spec.functions[*fi];
        for ov in &p.ovs {
            let names = rust_param_names(&ov.params);
            let args: Vec<String> = ov.params.iter().zip(&names).map(|(p, n)| format!("{n}: {}", trait_param(p))).collect();
            let _ = writeln!(o, "    /// `{}`", doc_sig(&spec.module, f, &ov.params));
            if !f.owners.is_empty() {
                let _ = writeln!(o, "    ///\n    /// C++ owners: {}.", f.owners.join(", "));
            }
            let _ = writeln!(
                o,
                "    fn {}(&mut self{}{}) -> PyResult<{}> {{\n        Err(PyError::NotImplemented(\"{}.{}\"))\n    }}",
                ov.rust_name,
                if args.is_empty() { "" } else { ", " },
                args.join(", "),
                trait_ret(&p.ret),
                spec.module,
                f.name
            );
        }
    }
    let _ = writeln!(o, "}}\n");
    let _ = writeln!(o, "thread_local! {{\n    static API: RefCell<Option<Box<dyn {tname}>>> = const {{ RefCell::new(None) }};\n}}\n");
    let _ = writeln!(o, "/// Installs the implementation (call on the Python thread before the interpreter runs scripts).");
    let _ = writeln!(o, "pub fn set_api(api: Box<dyn {tname}>) {{\n    API.with(|a| *a.borrow_mut() = Some(api));\n}}\n");
    let _ = writeln!(o, "fn with_api<R>(f: impl FnOnce(&mut dyn {tname}) -> R) -> Option<R> {{\n    API.with(|a| a.borrow_mut().as_mut().map(|b| f(b.as_mut())))\n}}\n");
    let _ = glue_outs;
    for (fi, p) in &plans {
        let f = &spec.functions[*fi];
        for ov in &p.ovs {
            let names = rust_param_names(&ov.params);
            let mut sig: Vec<String> = ov.params.iter().zip(&names).map(|(p, n)| format!("{n}: {}", glue_param(p))).collect();
            let mut writes = String::new();
            match &p.ret {
                Ty::None => {}
                Ty::Str => {
                    sig.push("out0: *mut *const c_char".into());
                    writes.push_str("unsafe { *out0 = keep_str(v) };");
                }
                Ty::Bytes => {
                    sig.push("out0: *mut *const u8".into());
                    sig.push("out0_len: *mut usize".into());
                    writes.push_str("let (p, n) = keep_bytes(v); unsafe { *out0 = p; *out0_len = n };");
                }
                Ty::Tuple(items) => {
                    for (i, t) in items.iter().enumerate() {
                        if *t == Ty::Str {
                            sig.push(format!("out{i}: *mut *const c_char"));
                            writes.push_str(&format!("unsafe {{ *out{i} = keep_str(v.{i}) }}; "));
                        } else {
                            sig.push(format!("out{i}: *mut {}", rust_type(t)));
                            writes.push_str(&format!("unsafe {{ *out{i} = v.{i} }}; "));
                        }
                    }
                }
                Ty::List(e) => {
                    if **e == Ty::Str {
                        sig.push("out0: *mut *const *const c_char".into());
                        sig.push("out0_len: *mut usize".into());
                        writes.push_str("let (p, n) = keep_strs(v); unsafe { *out0 = p; *out0_len = n };");
                    } else {
                        sig.push(format!("out0: *mut *const {}", rust_type(e)));
                        sig.push("out0_len: *mut usize".into());
                        writes.push_str("let (p, n) = keep_vec(v); unsafe { *out0 = p; *out0_len = n };");
                    }
                }
                t => {
                    sig.push(format!("out0: *mut {}", rust_type(t)));
                    writes.push_str("unsafe { *out0 = v };");
                }
            }
            let conv: Vec<String> = ov.params.iter().zip(&names).map(|(p, n)| glue_convert(p, n)).collect();
            let _ = writeln!(o, "/// C entry point for `{}`.", doc_sig(&spec.module, f, &ov.params));
            let _ = writeln!(o, "#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn m2_{ident}_{}({}) -> M2Result {{", ov.c_name, sig.join(", "));
            let _ = writeln!(o, "    match with_api(|api| api.{}({})) {{", ov.rust_name, conv.join(", "));
            let _ = writeln!(o, "        None => no_api(\"{}\"),", spec.module);
            let _ = writeln!(o, "        Some(Err(e)) => fail(e),");
            let _ = writeln!(o, "        Some(Ok({})) => {{\n            {writes}\n            ok()\n        }}", if matches!(p.ret, Ty::None) { "_v" } else { "v" });
            let _ = writeln!(o, "    }}\n}}\n");
        }
    }
    if !skipped.is_empty() {
        let _ = writeln!(o, "// Not generated (hand-written shim needed):");
        for (n, why) in skipped {
            let _ = writeln!(o, "//   {n}: {}", why.replace('\n', " "));
        }
    }
    let _ = rust_ident;
    o
}

pub fn write_all(specs: &[ModuleSpec], out: &Path) -> Result<(), String> {
    let dir = out.join("rust");
    std::fs::create_dir_all(&dir).map_err(|e| e.to_string())?;
    std::fs::write(dir.join("support.rs"), SUPPORT_RS).map_err(|e| e.to_string())?;
    let mut modrs = String::from("//! Generated by m2-modgen. Module glue; see crates/m2-modgen/README.md.\n#![allow(non_snake_case)]\npub mod support;\n");
    for s in specs.iter().filter(|s| !s.module.starts_with('(') && !s.functions.is_empty()) {
        let id = module_ident(&s.module);
        std::fs::write(dir.join(format!("{id}.rs")), generate_module(s)).map_err(|e| e.to_string())?;
        modrs.push_str(&format!("pub mod {id};\n"));
    }
    std::fs::write(dir.join("mod.rs"), modrs).map_err(|e| e.to_string())
}
