//! `MODULES.md`: the Phase 5 work breakdown, computed from the specs.

use crate::conformance::Diff;
use crate::spec::{ModuleSpec, Ty};
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

/// Recommended order (docs/bevy-port-plan.md, Phase 5), with the reason for each step.
const ORDER: &[(&str, &[&str], &str)] = &[
    ("1. Leaf modules, no C++ state", &["dbg", "time", "math", "pack", "fly", "profiler", "eventMgr"], "Pure functions or one-line forwards. `dbg`/`time`/`math`/`pack` are already proven by the real-build test; they validate the generator in the Bevy host first."),
    ("2. Process and platform services", &["app", "systemSetting", "snd", "ime", "ServerStateChecker"], "Each wraps one singleton (`CPythonApplication`, `CPythonSystem`, `CSoundManager`, IME, server pinger) that the Rust client replaces with Bevy resources. `app.Loop` is the entry point where Bevy takes over (rust_port.md, finding 1)."),
    ("3. Window system", &["wndMgr", "grp", "grpImage", "grpText", "grpThing"], "The UI tree and 2D drawing: required before any script can show a window. Handles are pointers passed as Python ints (`handle:*` types), so Rust must hand out stable ids. A large callback surface (`PythonWindow` events into Python)."),
    ("4. Network", &["net"], "Needs the packet layer (Phase 4). The most callback sites into Python (phase and packet handlers); the module itself is mostly thin sends."),
    ("5. World and actors", &["player", "chr", "chrmgr", "background", "item", "skill", "nonplayer"], "Depend on the game state ported in Phases 3-4. `player` has the most state (130 functions, 191 constants): port it in groups by owner (`CPythonPlayer` slots, skills, quick slots, party)."),
    ("6. The rest", &["quest", "guild", "shop", "safebox", "exchange", "messenger", "miniMap", "textTail", "effect", "event", "chat"], "Independent, mostly data-in/data-out; each can be a separate Rust module with its own trait."),
];

fn pct(a: usize, b: usize) -> String {
    if b == 0 { "n/a".into() } else { format!("{:.1}%", 100.0 * a as f64 / b as f64) }
}

pub fn render(specs: &[ModuleSpec], diff: &Diff) -> String {
    let mods: Vec<&ModuleSpec> = specs.iter().filter(|s| !s.module.starts_with('(')).collect();
    let nf: usize = mods.iter().map(|s| s.functions.len()).sum();
    let classified: usize = mods.iter().flat_map(|s| &s.functions).filter(|f| f.status == "classified").count();
    let args_ok: usize = mods.iter().flat_map(|s| &s.functions).filter(|f| f.args_ok()).count();
    let ret_ok: usize = mods.iter().flat_map(|s| &s.functions).filter(|f| f.returns_ok()).count();
    let consts: usize = mods.iter().map(|s| s.constants.len()).sum();
    let cbs: usize = specs.iter().map(|s| s.callbacks.len()).sum();
    let mut o = String::new();
    let _ = writeln!(o, "# Python modules: Phase 5 work breakdown\n");
    let _ = writeln!(o, "Generated by `m2-modgen report` from `modules/*.toml`; do not edit. See [README.md](README.md) for the spec format and the tools.\n");
    let _ = writeln!(o, "## Summary\n");
    let _ = writeln!(o, "- {} Python modules, {} functions, {} constants, {} callback sites into Python.", mods.len(), nf, consts, cbs);
    let _ = writeln!(o, "- Fully classified (arguments **and** return value): **{classified} / {nf} ({})**.", pct(classified, nf));
    let _ = writeln!(o, "- Arguments classified: {args_ok} / {nf} ({}); return value classified: {ret_ok} / {nf} ({}).", pct(args_ok, nf), pct(ret_ok, nf));
    let _ = writeln!(
        o,
        "- Conformance with the API snapshots: {} names compared, {} missing, {} extra, {} kind/value mismatches ({} build-conditional names are informational).",
        diff.compared,
        diff.missing.len(),
        diff.extra.len(),
        diff.kind_mismatch.len(),
        diff.conditional_extra.len()
    );
    let nstub: usize = mods.iter().flat_map(|s| &s.functions).filter(|f| f.status != "classified").count();
    let _ = writeln!(o, "- The generator emits shims for every classified function; the {nstub} others need a hand-written shim (listed below).\n");

    // Per-module table.
    let _ = writeln!(o, "## Modules\n");
    let _ = writeln!(o, "| Module | Functions | Classified | Partial | Unclassified | Constants | Callback sites | C++ managers touched |");
    let _ = writeln!(o, "|---|---:|---:|---:|---:|---:|---:|---|");
    let mut by_name: Vec<&&ModuleSpec> = mods.iter().collect();
    by_name.sort_by(|a, b| a.module.to_lowercase().cmp(&b.module.to_lowercase()));
    for s in &by_name {
        let c = s.functions.iter().filter(|f| f.status == "classified").count();
        let p = s.functions.iter().filter(|f| f.status == "partial").count();
        let u = s.functions.iter().filter(|f| f.status == "unclassified").count();
        let mut owners: BTreeMap<&str, usize> = BTreeMap::new();
        for f in &s.functions {
            for ow in &f.owners {
                *owners.entry(ow.as_str()).or_default() += 1;
            }
        }
        let mut ov: Vec<(&str, usize)> = owners.into_iter().collect();
        ov.sort_by(|a, b| b.1.cmp(&a.1).then(a.0.cmp(b.0)));
        let txt: Vec<String> = ov.iter().take(6).map(|(n, k)| format!("`{n}` ({k})")).collect();
        let more = if ov.len() > 6 { format!(" +{} more", ov.len() - 6) } else { String::new() };
        let _ = writeln!(o, "| `{}` | {} | {c} | {p} | {u} | {} | {} | {}{more} |", s.module, s.functions.len(), s.constants.len(), s.callbacks.len(), if txt.is_empty() { "-".into() } else { txt.join(", ") });
    }

    // Managers.
    let _ = writeln!(o, "\n## C++ managers and the modules that call them\n");
    let _ = writeln!(o, "Each manager becomes a Rust trait or resource; this is the grouping for the trait split.\n");
    let mut mgr: BTreeMap<&str, BTreeMap<&str, usize>> = BTreeMap::new();
    for s in &mods {
        for f in &s.functions {
            for ow in &f.owners {
                *mgr.entry(ow.as_str()).or_default().entry(s.module.as_str()).or_default() += 1;
            }
        }
    }
    let mut ml: Vec<(&&str, &BTreeMap<&str, usize>)> = mgr.iter().collect();
    ml.sort_by(|a, b| b.1.values().sum::<usize>().cmp(&a.1.values().sum::<usize>()).then(a.0.cmp(b.0)));
    let _ = writeln!(o, "| Manager | Calls | Modules |\n|---|---:|---|");
    for (name, m) in ml.iter() {
        let total: usize = m.values().sum();
        let txt: Vec<String> = m.iter().map(|(k, v)| format!("{k} ({v})")).collect();
        let _ = writeln!(o, "| `{name}` | {total} | {} |", txt.join(", "));
    }

    // Callbacks.
    let _ = writeln!(o, "\n## Callbacks Rust must make back into Python\n");
    let _ = writeln!(
        o,
        "`PyCallClassMemberFunc` sites (calls of a method on a Python object that a script registered, e.g. `player.SetGameWindow(self)`), attributed to a module by source file. The Rust host needs one callback entry point per distinct handler name; the arguments are built at each site.\n"
    );
    let _ = writeln!(o, "| Module | Sites | Distinct handlers | Examples |\n|---|---:|---:|---|");
    for s in specs {
        if s.callbacks.is_empty() {
            continue;
        }
        let h: BTreeSet<&str> = s.callbacks.iter().map(|c| c.handler.as_str()).collect();
        let ex: Vec<String> = h.iter().take(5).map(|x| format!("`{x}`")).collect();
        let _ = writeln!(o, "| `{}` | {} | {} | {} |", s.module, s.callbacks.len(), h.len(), ex.join(", "));
    }
    let _ = writeln!(o, "\nFull lists with file and line are in the `[[callback]]` tables of each spec.");
    let _ = writeln!(o, "\nFunctions that accept a Python object (candidates for handler registration or opaque callbacks):\n");
    for s in &mods {
        let names: Vec<String> = s
            .functions
            .iter()
            .filter(|f| f.overloads.iter().flatten().any(|p| p.contains(": object")))
            .map(|f| f.name.clone())
            .collect();
        if !names.is_empty() {
            let _ = writeln!(o, "- `{}`: {}", s.module, names.iter().map(|n| format!("`{n}`")).collect::<Vec<_>>().join(", "));
        }
    }

    // Unclassified.
    let _ = writeln!(o, "\n## Functions that need a hand-written shim\n");
    let _ = writeln!(o, "| Function | Status | Reason |\n|---|---|---|");
    for s in &mods {
        for f in s.functions.iter().filter(|f| f.status != "classified") {
            let _ = writeln!(o, "| `{}.{}` | {} | {} |", s.module, f.name, f.status, f.unclassified.join("; ").replace('|', "\\|"));
        }
    }

    // Quirks.
    let _ = writeln!(o, "\n## Quirks found in the C++ (candidates for `c++_rust_bugs.md`)\n");
    for s in &mods {
        for f in s.functions.iter().filter(|f| !f.quirks.is_empty()) {
            let _ = writeln!(o, "- `{}.{}` ({}:{}): {}", s.module, f.name, f.file, f.line, f.quirks.join("; "));
        }
    }

    // Return types.
    let mut kinds: BTreeMap<String, usize> = BTreeMap::new();
    for f in mods.iter().flat_map(|s| &s.functions) {
        let k = match f.return_ty() {
            Ty::Tuple(_) => "tuple".to_string(),
            Ty::List(_) => "list".to_string(),
            t => t.to_string(),
        };
        *kinds.entry(k).or_default() += 1;
    }
    let _ = writeln!(o, "\n## Return types\n");
    let _ = writeln!(o, "| Type | Functions |\n|---|---:|");
    let mut kv: Vec<_> = kinds.into_iter().collect();
    kv.sort_by(|a, b| b.1.cmp(&a.1).then(a.0.cmp(&b.0)));
    for (k, n) in kv {
        let _ = writeln!(o, "| `{k}` | {n} |");
    }

    // Order.
    let _ = writeln!(o, "\n## Recommended porting order\n");
    let size = |name: &str| mods.iter().find(|s| s.module == name).map(|s| s.functions.len()).unwrap_or(0);
    for (title, names, why) in ORDER {
        let total: usize = names.iter().map(|n| size(n)).sum();
        let list: Vec<String> = names.iter().map(|n| format!("`{n}` ({})", size(n))).collect();
        let _ = writeln!(o, "### {title} - {total} functions\n\n{}\n\n{why}\n", list.join(", "));
    }
    let listed: BTreeSet<&str> = ORDER.iter().flat_map(|(_, n, _)| n.iter().copied()).collect();
    let missing: Vec<&str> = mods.iter().map(|s| s.module.as_str()).filter(|m| !listed.contains(m)).collect();
    if !missing.is_empty() {
        let _ = writeln!(o, "Not placed in the order above: {}.\n", missing.join(", "));
    }
    let _ = writeln!(
        o,
        "Method per step: regenerate the shim for the module with the empty prefix (the generated `initX` replaces the hand-written one), implement the generated trait in Rust, run the unmodified scripts, and keep the API snapshot test green. Functions in the table above are ported by hand first and then described in the spec manually."
    );
    o
}
