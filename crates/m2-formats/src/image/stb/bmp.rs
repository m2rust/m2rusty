//! stb_image's BMP loader (`stbi__bmp_*`): uncompressed and bitfield BMPs of
//! 1, 4, 8, 16, 24 and 32 bits with a 12, 40, 56, 108 or 124 byte header. RLE
//! and embedded JPEG/PNG are rejected, as in stb.

use super::{Ctx, Info, MAX_DIMENSIONS, Rgba, mad3sizes_valid};

/// `stbi__bmp_test`.
pub(super) fn test(data: &[u8]) -> bool {
    let mut s = Ctx::new(data);
    if s.get8() != b'B' || s.get8() != b'M' {
        return false;
    }
    s.get32le(); // filesize
    s.get16le(); // reserved
    s.get16le(); // reserved
    s.get32le(); // data offset
    matches!(s.get32le(), 12 | 40 | 56 | 108 | 124)
}

#[derive(Default)]
struct BmpData {
    bpp: i32,
    offset: i32,
    hsz: i32,
    mr: u32,
    mg: u32,
    mb: u32,
    ma: u32,
    all_a: u32,
    extra_read: i32,
}

/// `stbi__high_bit`: index of the highest set bit, -1 for 0.
fn high_bit(z: u32) -> i32 {
    if z == 0 { -1 } else { 31 - z.leading_zeros() as i32 }
}

/// `stbi__shiftsigned`: extracts an N-bit value and spreads it over 8 bits.
fn shiftsigned(mut v: u32, shift: i32, bits: i32) -> i32 {
    const MUL_TABLE: [u32; 9] = [0, 0xff, 0x55, 0x49, 0x11, 0x21, 0x41, 0x81, 0x01];
    const SHIFT_TABLE: [u32; 9] = [0, 0, 0, 1, 0, 2, 4, 6, 0];
    if shift < 0 {
        v <<= -shift;
    } else {
        v >>= shift;
    }
    v >>= 8 - bits;
    ((v.wrapping_mul(MUL_TABLE[bits as usize])) as i32) >> SHIFT_TABLE[bits as usize]
}

/// `stbi__bmp_set_mask_defaults`.
fn set_mask_defaults(info: &mut BmpData, compress: i32) -> bool {
    if compress == 3 {
        return true; // BI_BITFIELDS specifies masks explicitly
    }
    if compress == 0 {
        if info.bpp == 16 {
            info.mr = 31 << 10;
            info.mg = 31 << 5;
            info.mb = 31;
        } else if info.bpp == 32 {
            info.mr = 0xff << 16;
            info.mg = 0xff << 8;
            info.mb = 0xff;
            info.ma = 0xff << 24;
            info.all_a = 0; // if all_a is 0 at end, then we loaded alpha channel but it was all 0
        } else {
            info.mr = 0;
            info.mg = 0;
            info.mb = 0;
            info.ma = 0;
        }
        return true;
    }
    false
}

/// `stbi__bmp_parse_header`; fills `img_x`, `img_y` (as `int`s: a negative height
/// means top-down).
fn parse_header(s: &mut Ctx, info: &mut BmpData) -> Option<(u32, u32)> {
    if s.get8() != b'B' || s.get8() != b'M' {
        return None;
    }
    s.get32le(); // filesize
    s.get16le();
    s.get16le();
    info.offset = s.get32le() as i32;
    let hsz = s.get32le() as i32;
    info.hsz = hsz;
    info.mr = 0;
    info.mg = 0;
    info.mb = 0;
    info.ma = 0;
    info.extra_read = 14;

    if info.offset < 0 {
        return None;
    }
    if !matches!(hsz, 12 | 40 | 56 | 108 | 124) {
        return None;
    }
    let (x, y);
    if hsz == 12 {
        x = s.get16le() as u32;
        y = s.get16le() as u32;
    } else {
        x = s.get32le();
        y = s.get32le();
    }
    if s.get16le() != 1 {
        return None;
    }
    info.bpp = s.get16le();
    if hsz != 12 {
        let compress = s.get32le() as i32;
        if compress == 1 || compress == 2 {
            return None; // RLE
        }
        if compress >= 4 {
            return None; // JPEG/PNG
        }
        if compress == 3 && info.bpp != 16 && info.bpp != 32 {
            return None;
        }
        s.get32le(); // sizeof
        s.get32le(); // hres
        s.get32le(); // vres
        s.get32le(); // colorsused
        s.get32le(); // max important
        if hsz == 40 || hsz == 56 {
            if hsz == 56 {
                s.get32le();
                s.get32le();
                s.get32le();
                s.get32le();
            }
            if info.bpp == 16 || info.bpp == 32 {
                if compress == 0 {
                    set_mask_defaults(info, compress);
                } else if compress == 3 {
                    info.mr = s.get32le();
                    info.mg = s.get32le();
                    info.mb = s.get32le();
                    info.extra_read += 12;
                    // not documented, but generated by photoshop and handled by mspaint
                    if info.mr == info.mg && info.mg == info.mb {
                        return None;
                    }
                } else {
                    return None;
                }
            }
        } else {
            // V4/V5 header
            if hsz != 108 && hsz != 124 {
                return None;
            }
            info.mr = s.get32le();
            info.mg = s.get32le();
            info.mb = s.get32le();
            info.ma = s.get32le();
            if compress != 3 {
                // override mr/mg/mb unless in BI_BITFIELDS mode, as per docs
                set_mask_defaults(info, compress);
            }
            s.get32le(); // color space
            for _ in 0..12 {
                s.get32le(); // color space parameters
            }
            if hsz == 124 {
                s.get32le();
                s.get32le();
                s.get32le();
                s.get32le();
            }
        }
    }
    Some((x, y))
}

/// `stbi__bmp_info`.
pub(super) fn info(data: &[u8]) -> Option<Info> {
    let mut s = Ctx::new(data);
    let mut info = BmpData { all_a: 255, ..BmpData::default() };
    let (x, y) = parse_header(&mut s, &mut info)?;
    let components = if info.bpp == 24 && info.ma == 0xff00_0000 {
        3
    } else if info.ma != 0 {
        4
    } else {
        3
    };
    Some(Info { width: x, height: y, components })
}

/// `stbi__bmp_load` with `req_comp == 4`.
pub(super) fn load(data: &[u8]) -> Option<Rgba> {
    let mut s = Ctx::new(data);
    let mut info = BmpData { all_a: 255, ..BmpData::default() };
    let (img_x, raw_y) = parse_header(&mut s, &mut info)?;

    let flip_vertically = (raw_y as i32) > 0;
    let img_y = (raw_y as i32).unsigned_abs();

    if img_y > MAX_DIMENSIONS || img_x > MAX_DIMENSIONS {
        return None;
    }

    let (mr, mg, mb, ma) = (info.mr, info.mg, info.mb, info.ma);
    let mut all_a = info.all_a;

    let mut psize = 0i32;
    if info.hsz == 12 {
        if info.bpp < 24 {
            psize = (info.offset - info.extra_read - 24) / 3;
        }
    } else if info.bpp < 16 {
        psize = (info.offset - info.extra_read - info.hsz) >> 2;
    }
    if psize == 0 {
        // accept some number of extra bytes after the header, but if the offset points either to
        // before the header ends or implies a large amount of extra data, reject the file
        let bytes_read_so_far = s.pos as i32;
        let header_limit = 1024;
        let extra_data_limit = 256 * 4;
        if bytes_read_so_far <= 0 || bytes_read_so_far > header_limit {
            return None;
        }
        if info.offset < bytes_read_so_far || info.offset - bytes_read_so_far > extra_data_limit {
            return None;
        }
        s.skip(info.offset - bytes_read_so_far);
    }

    let img_n = if info.bpp == 24 && ma == 0xff00_0000 {
        3
    } else if ma != 0 {
        4
    } else {
        3
    };
    let target = 4usize; // req_comp >= 3: decode directly to 4

    // sanity-check size
    if !mad3sizes_valid(target as i32, img_x as i32, img_y as i32) {
        return None;
    }
    let (w, h) = (img_x as usize, img_y as usize);
    let mut out = Vec::new();
    out.try_reserve_exact(target * w * h).ok()?;
    out.resize(target * w * h, 0u8);

    if info.bpp < 16 {
        if psize == 0 || psize > 256 {
            return None;
        }
        let mut pal = [[0u8; 4]; 256];
        for p in pal.iter_mut().take(psize as usize) {
            p[2] = s.get8();
            p[1] = s.get8();
            p[0] = s.get8();
            if info.hsz != 12 {
                s.get8();
            }
            p[3] = 255;
        }
        s.skip(info.offset - info.extra_read - info.hsz - psize * if info.hsz == 12 { 3 } else { 4 });
        let width = match info.bpp {
            1 => (img_x + 7) >> 3,
            4 => (img_x + 1) >> 1,
            8 => img_x,
            _ => return None,
        } as i32;
        let pad = (-width) & 3;
        let mut z = 0;
        let mut put = |out: &mut Vec<u8>, c: usize| {
            out[z] = pal[c][0];
            out[z + 1] = pal[c][1];
            out[z + 2] = pal[c][2];
            out[z + 3] = 255;
            z += 4;
        };
        if info.bpp == 1 {
            for _ in 0..h {
                let mut bit_offset = 7;
                let mut v = i32::from(s.get8());
                for i in 0..w {
                    let color = ((v >> bit_offset) & 1) as usize;
                    put(&mut out, color);
                    if i + 1 == w {
                        break;
                    }
                    bit_offset -= 1;
                    if bit_offset < 0 {
                        bit_offset = 7;
                        v = i32::from(s.get8());
                    }
                }
                s.skip(pad);
            }
        } else {
            for _ in 0..h {
                let mut i = 0;
                while i < w {
                    let mut v = i32::from(s.get8());
                    let mut v2 = 0;
                    if info.bpp == 4 {
                        v2 = v & 15;
                        v >>= 4;
                    }
                    put(&mut out, v as usize);
                    if i + 1 == w {
                        break;
                    }
                    v = if info.bpp == 8 { i32::from(s.get8()) } else { v2 };
                    put(&mut out, v as usize);
                    i += 2;
                }
                s.skip(pad);
            }
        }
    } else {
        let (mut rshift, mut gshift, mut bshift, mut ashift) = (0, 0, 0, 0);
        let (mut rcount, mut gcount, mut bcount, mut acount) = (0, 0, 0, 0);
        let mut z = 0usize;
        let mut easy = 0;
        s.skip(info.offset - info.extra_read - info.hsz);
        let width = match info.bpp {
            24 => 3 * img_x as i32,
            16 => 2 * img_x as i32,
            _ => 0, // bpp = 32 and pad = 0
        };
        let pad = (-width) & 3;
        if info.bpp == 24 {
            easy = 1;
        } else if info.bpp == 32 && mb == 0xff && mg == 0xff00 && mr == 0x00ff_0000 && ma == 0xff00_0000 {
            easy = 2;
        }
        if easy == 0 {
            if mr == 0 || mg == 0 || mb == 0 {
                return None; // bad masks
            }
            rshift = high_bit(mr) - 7;
            rcount = mr.count_ones() as i32;
            gshift = high_bit(mg) - 7;
            gcount = mg.count_ones() as i32;
            bshift = high_bit(mb) - 7;
            bcount = mb.count_ones() as i32;
            ashift = high_bit(ma) - 7;
            acount = ma.count_ones() as i32;
            if rcount > 8 || gcount > 8 || bcount > 8 || acount > 8 {
                return None;
            }
        }
        for _ in 0..h {
            if easy != 0 {
                for _ in 0..w {
                    out[z + 2] = s.get8();
                    out[z + 1] = s.get8();
                    out[z] = s.get8();
                    z += 3;
                    let a = if easy == 2 { s.get8() } else { 255 };
                    all_a |= u32::from(a);
                    out[z] = a;
                    z += 1;
                }
            } else {
                for _ in 0..w {
                    let v = if info.bpp == 16 { s.get16le() as u32 } else { s.get32le() };
                    out[z] = shiftsigned(v & mr, rshift, rcount) as u8;
                    out[z + 1] = shiftsigned(v & mg, gshift, gcount) as u8;
                    out[z + 2] = shiftsigned(v & mb, bshift, bcount) as u8;
                    let a = if ma != 0 { shiftsigned(v & ma, ashift, acount) as u32 } else { 255 };
                    all_a |= a;
                    out[z + 3] = a as u8;
                    z += 4;
                }
            }
            s.skip(pad);
        }
    }

    // if alpha channel is all 0s, replace with all 255s
    if all_a == 0 {
        for px in out.chunks_exact_mut(4) {
            px[3] = 255;
        }
    }

    if flip_vertically {
        for j in 0..h / 2 {
            let (top, bottom) = out.split_at_mut((h - 1 - j) * w * target);
            top[j * w * target..(j + 1) * w * target].swap_with_slice(&mut bottom[..w * target]);
        }
    }

    Some(Rgba { width: img_x, height: img_y, components: img_n, pixels: out })
}
