/// The base letter of each `COMPOSED` row (`ComposeTone`'s row switch).
const ROW_BASE: [u32; 24] = [
    0x41, 0x61, 0x102, 0x103, 0xc2, 0xe2, 0x45, 0x65, 0xca, 0xea, 0x49, 0x69, 0x4f, 0x6f, 0xd4, 0xf4, 0x1a0, 0x1a1,
    0x55, 0x75, 0x1af, 0x1b0, 0x59, 0x79,
];

/// The CP1258 byte of each row's base letter (`DecomposeLetter`).
const ROW_LETTER: [u8; 24] = [
    b'A', b'a', 0xc3, 0xe3, 0xc2, 0xe2, b'E', b'e', 0xca, 0xea, b'I', b'i', b'O', b'o', 0xd4, 0xf4, 0xd5, 0xf5, b'U',
    b'u', 0xdd, 0xfd, b'Y', b'y',
];

/// The combining tone of each `COMPOSED` column, and its CP1258 byte
/// (`ComposeTone`'s column switch, `DecomposeTone`).
const TONES: [(u32, u8); 5] = [(0x0301, 0xec), (0x0300, 0xcc), (0x0309, 0xd2), (0x0303, 0xde), (0x0323, 0xf2)];

/// `ComposeTone`: the letter with the tone, or the letter unchanged (the
/// tone is then dropped).
fn compose_tone(prev: u32, tone: u32) -> u32 {
    let Some(col) = TONES.iter().position(|&(t, _)| t == tone) else {
        return prev;
    };
    match ROW_BASE.iter().position(|&b| b == prev) {
        Some(row) => u32::from(COMPOSED[row][col]),
        None => prev,
    }
}

/// Row and column of a precomposed letter.
fn find_composed(c: u32) -> Option<(usize, usize)> {
    COMPOSED
        .iter()
        .enumerate()
        .find_map(|(row, cols)| cols.iter().position(|&x| u32::from(x) == c).map(|col| (row, col)))
}

/// `DecomposeLetter`.
fn decompose_letter(c: u32) -> Option<u8> {
    if let Some((row, _)) = find_composed(c) {
        return Some(ROW_LETTER[row]);
    }
    match c {
        0x0102 => Some(0xc3),
        0x0103 => Some(0xe3),
        0x0110 => Some(0xd0),
        0x0111 => Some(0xf0),
        0x01a0 => Some(0xd5),
        0x01a1 => Some(0xf5),
        0x01af => Some(0xdd),
        0x01b0 => Some(0xfd),
        0x20ab => Some(0xfe),
        0x201c | 0x201d => Some(b'"'),
        // wchar_t is signed: values from 0x80000000 up are negative and
        // pass, truncated to their low byte.
        _ if (c as i32) < 256 => Some(c as u8),
        _ => None,
    }
}

/// `DecomposeTone`.
fn decompose_tone(c: u32) -> Option<u8> {
    find_composed(c).map(|(_, col)| TONES[col].1)
}

/// `EL_String_Decode_Vietnamese`: decodes into `wide`, returning the number
/// of characters written. An empty `wide` writes nothing and returns 0 (no
/// size query, unlike `MultiByteToWideChar`).
pub fn decode(multi: &[u8], wide: &mut [u32]) -> usize {
    let Some((&first, rest)) = multi.split_first() else {
        return 0;
    };
    let mut dest = 0;
    let mut push = |c: u32| {
        if dest < wide.len() {
            wide[dest] = c;
            dest += 1;
        }
    };

    let mut prev = u32::from(TO_UNICODE[usize::from(first)]);
    for &b in rest {
        let unicode = u32::from(TO_UNICODE[usize::from(b)]);
        if TONES.iter().any(|&(t, _)| t == unicode) {
            prev = compose_tone(prev, unicode);
        } else {
            push(prev);
            prev = unicode;
        }
    }
    push(prev);
    dest
}

/// `EL_String_Encode_Vietnamese`: encodes into `multi`, returning the number
/// of bytes written. Characters without a CP1258 letter are dropped; a tone
/// that no longer fits is dropped too.
pub fn encode(wide: &[u32], multi: &mut [u8]) -> usize {
    let mut dest = 0;
    for &c in wide {
        if dest >= multi.len() {
            break;
        }
        if let Some(letter) = decompose_letter(c) {
            multi[dest] = letter;
            dest += 1;
        }
        if let Some(tone) = decompose_tone(c)
            && dest < multi.len()
        {
            multi[dest] = tone;
            dest += 1;
        }
    }
    dest
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tones_compose_once() {
        let mut wide = [0; 8];
        let n = decode(b"Vie\xea\xf2t", &mut wide);
        assert_eq!(wide[..n], [0x56, 0x69, 0x65, 0x1ec7, 0x74]);
        // A second tone is dropped; a leading tone stays a combining mark.
        let n = decode(b"a\xec\xcc", &mut wide);
        assert_eq!(wide[..n], [0xe1]);
        let n = decode(b"\xecA", &mut wide);
        assert_eq!(wide[..n], [0x301, 0x41]);
    }

    #[test]
    fn encode_splits_and_truncates() {
        let mut multi = [0; 8];
        let n = encode(&[0x1ec7, 0x4e00, 0x201c], &mut multi);
        assert_eq!(multi[..n], [0xea, 0xf2, b'"']);
        let mut one = [0; 1];
        assert_eq!(encode(&[0xe1], &mut one), 1);
        assert_eq!(one, [b'a']);
        assert_eq!(encode(&[0xffff_ff41], &mut multi), 1);
        assert_eq!(multi[0], 0x41);
    }
}
