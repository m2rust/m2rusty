//! Texture loader: `.dds .tga .jpg .jpeg .bmp .png` to a Bevy [`Image`].
//!
//! Everything is decoded on the CPU by [`m2_formats::image`], which reproduces
//! the original client's decoders (its own DXT1/3/5 decompressor, its own TGA
//! reader and the stb_image JPEG/TGA/BMP/PNG loaders). No GPU-compressed
//! upload is used, so the pixels are identical on every platform.
//!
//! # Format and colour
//!
//! The image is [`TextureFormat::Rgba8Unorm`], **not** `Rgba8UnormSrgb`: the
//! fixed-function pipeline of the original client blends and lights in gamma
//! space and never converts, so the texels must reach the shader untouched.
//!
//! # Channel order
//!
//! `m2_formats` hands out `0xAARRGGBB` words (DDS) or B,G,R,A bytes (stb based
//! paths, as `Platform_DecodeImage` does). Both are converted to R,G,B,A bytes
//! here; [`tests`] checks it against a known real file whose corner colours
//! are known.
//!
//! # Mip levels
//!
//! A DDS keeps the mip levels it carries, as far as they are whole 4x4 blocks
//! (the client's decompressor skips smaller ones: every level with a side below
//! 4 is dropped, the GPU chain simply ends there). Other formats have no mip
//! chain; the original client let D3DX generate one, which is not reproduced
//! (the chain can be generated by the material crate if needed).

use bevy::asset::{AssetLoader, LoadContext, RenderAssetUsages, io::Reader};
use bevy::image::{Image, ImageAddressMode, ImageSampler, ImageSamplerDescriptor};
use bevy::render::render_resource::{Extent3d, TextureDimension, TextureFormat};
use m2_formats::image::{DxtcImage, PixFormat, decode_image};
use serde::{Deserialize, Serialize};

use crate::Error;

/// Settings for [`M2ImageLoader`] (set with `load_with_settings`).
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct M2ImageSettings {
    /// Address mode: wrap (`true`, Direct3D's default and what almost all game
    /// textures use) or clamp to edge (`false`; UI, sky and terrain edges).
    pub repeat: bool,
}

impl Default for M2ImageSettings {
    fn default() -> Self {
        Self { repeat: true }
    }
}

/// Loads game textures into [`Image`] assets.
#[derive(Default, bevy::reflect::TypePath)]
pub struct M2ImageLoader;

impl AssetLoader for M2ImageLoader {
    type Asset = Image;
    type Settings = M2ImageSettings;
    type Error = Error;

    async fn load(
        &self,
        reader: &mut dyn Reader,
        settings: &M2ImageSettings,
        load_context: &mut LoadContext<'_>,
    ) -> Result<Image, Error> {
        let mut bytes = Vec::new();
        reader.read_to_end(&mut bytes).await?;
        decode(&bytes, settings).map_err(|e| Error::Decode(format!("{}: {e}", load_context.path())))
    }

    fn extensions(&self) -> &[&str] {
        &["dds", "tga", "jpg", "jpeg", "bmp", "png"]
    }
}

/// Decodes a texture file to an RGBA8 [`Image`] (see the module documentation).
pub fn decode(bytes: &[u8], settings: &M2ImageSettings) -> Result<Image, String> {
    let (width, height, levels) = if bytes.starts_with(b"DDS ") {
        decode_dds(bytes)?
    } else {
        let img = decode_image(bytes).ok_or("unsupported or corrupt image")?;
        let mut rgba = img.bgra;
        for px in rgba.chunks_exact_mut(4) {
            px.swap(0, 2);
        }
        (img.width, img.height, vec![rgba])
    };
    if width == 0 || height == 0 {
        return Err("empty image".into());
    }

    let mip_level_count = levels.len() as u32;
    let data: Vec<u8> = levels.concat();
    let mut image = Image::new(
        Extent3d { width, height, depth_or_array_layers: 1 },
        TextureDimension::D2,
        data,
        TextureFormat::Rgba8Unorm,
        RenderAssetUsages::default(),
    );
    image.texture_descriptor.mip_level_count = mip_level_count;
    let mode = if settings.repeat { ImageAddressMode::Repeat } else { ImageAddressMode::ClampToEdge };
    image.sampler = ImageSampler::Descriptor(ImageSamplerDescriptor {
        address_mode_u: mode,
        address_mode_v: mode,
        address_mode_w: mode,
        ..ImageSamplerDescriptor::linear()
    });
    Ok(image)
}

/// `(width, height, RGBA8 bytes per mip level)`.
fn decode_dds(bytes: &[u8]) -> Result<(u32, u32, Vec<Vec<u8>>), String> {
    let header = DxtcImage::load_header(bytes).ok_or("DDS is not DXT1/DXT3/DXT5")?;
    if header.width <= 0 || header.height <= 0 {
        return Err(format!("bad DDS size {}x{}", header.width, header.height));
    }
    if header.comp_format == PixFormat::Unknown {
        return Err("unknown DDS format".into());
    }
    let (width, height) = (header.width as u32, header.height as u32);

    let mut levels = Vec::new();
    for level in 0..header.mip_map_count {
        let (w, h) = (width >> level, height >> level);
        if level > 0 && (w < 4 || h < 4) {
            break;
        }
        let Some(comp) = header.copy(bytes, level as usize) else {
            if level == 0 {
                return Err("truncated DDS".into());
            }
            break;
        };
        let Some(pixels) = header.decompress(level, comp) else {
            if level == 0 {
                return Err("truncated DDS".into());
            }
            break;
        };
        let mut rgba = Vec::with_capacity(pixels.len() * 4);
        for p in pixels {
            rgba.extend_from_slice(&[(p >> 16) as u8, (p >> 8) as u8, p as u8, (p >> 24) as u8]);
        }
        levels.push(rgba);
    }
    if levels.is_empty() {
        return Err("DDS without data".into());
    }
    Ok((width, height, levels))
}
