#!/usr/bin/env perl
# Generates crates/m2-net/src/stream/seq_table.rs from `s_bSequenceTable` in
# neoeter/src/render/NetStream.cpp. Run from the repository root.
use strict;
use warnings;

local $/;
open my $f, '<', 'neoeter/src/render/NetStream.cpp' or die $!;
my $cpp = <$f>;
my ($body) = $cpp =~ /s_bSequenceTable\[SEQUENCE_TABLE_SIZE\]\s*=\s*\{(.*?)\};/s or die "sequence table";
my @b = map { hex($_) } ($body =~ /0x([0-9a-fA-F]+)/g);
my $s = "// \@generated by tools/differential/net/gen_seq.pl from neoeter/src/render/NetStream.cpp.\n";
$s .= "// `s_bSequenceTable` (SEQUENCE_TABLE_SIZE = 32768 entries).\n";
$s .= "pub static SEQUENCE_TABLE: [u8; " . scalar(@b) . "] = [\n";
for (my $i = 0; $i < @b; $i += 16) {
    my $e = $i + 15 < $#b ? $i + 15 : $#b;
    $s .= "    " . join(", ", map { sprintf "0x%02x", $_ } @b[$i .. $e]) . ",\n";
}
$s .= "];\n";
open my $o, '>', 'crates/m2-net/src/stream/seq_table.rs' or die $!;
print $o $s;
close $o;
print STDERR scalar(@b) . " explicit bytes\n";
